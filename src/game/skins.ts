export type PriceTierCategory = 'starter' | 'basic' | 'normal' | 'vip';

export function getItemPriceTier(priceCytes: number): PriceTierCategory {
  if (priceCytes <= 0) return 'starter';
  if (priceCytes <= 350) return 'basic';
  if (priceCytes <= 3000) return 'normal';
  return 'vip';
}

